<script>
    window.__mentors = @json($mentorData);

    function openMentorModal(index) {
        var m = window.__mentors[index];
        if (!m) return;
        document.getElementById('mentor-modal-img').src   = m.image;
        document.getElementById('mentor-modal-img').alt   = m.name;
        document.getElementById('mentor-modal-name').textContent = m.name;
        document.getElementById('mentor-modal-role').textContent = '(' + m.role + ')';
        document.getElementById('mentor-modal-desc').textContent = m.description;

        var modal = document.getElementById('mentor-modal');
        modal.classList.remove('hidden');
        modal.classList.add('flex');
        document.body.style.overflow = 'hidden';
        stopMentorsAuto();
    }

    function closeMentorModal() {
        var modal = document.getElementById('mentor-modal');
        modal.classList.add('hidden');
        modal.classList.remove('flex');
        document.body.style.overflow = '';
        startMentorsAuto();
    }

    /* ── Auto-scroll carousel (4 at a time) ── */
    var mentorsAutoTimer = null;

    function mentorsAutoStep() {
        var track = document.getElementById('mentors-track');
        if (!track) return;
        var card = track.querySelector('[data-card]');
        if (!card) return;
        var gap = parseFloat(getComputedStyle(track).columnGap) || 0;
        var amount = card.offsetWidth + gap;
        if (track.scrollLeft + track.clientWidth >= track.scrollWidth - 2) {
            track.scrollTo({ left: 0, behavior: 'smooth' });
        } else {
            track.scrollBy({ left: amount, behavior: 'smooth' });
        }
    }

    function startMentorsAuto() {
        stopMentorsAuto();
        mentorsAutoTimer = setInterval(mentorsAutoStep, 2500);
    }

    function stopMentorsAuto() {
        if (mentorsAutoTimer) { clearInterval(mentorsAutoTimer); mentorsAutoTimer = null; }
    }

    (function () {
        var track = document.getElementById('mentors-track');
        if (!track) return;
        startMentorsAuto();
        track.addEventListener('mouseenter', stopMentorsAuto);
        track.addEventListener('mouseleave', startMentorsAuto);
        track.addEventListener('touchstart', stopMentorsAuto, { passive: true });
    })();
</script>
